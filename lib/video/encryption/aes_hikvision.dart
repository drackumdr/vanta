import 'dart:typed_data';

import 'verification_key.dart';

/// Implementación pura en Dart de AES-128 (FIPS 197) en modo ECB para descifrado
/// de flujos de video Hikvision.
///
/// Diseñado para cero dependencias externas y máxima portabilidad en Windows, Linux y Android.
class Aes128Hikvision {
  final Uint32List _expandedKey = Uint32List(44);

  Aes128Hikvision(VerificationKey key) {
    _expandKey(key.bytes);
  }

  Aes128Hikvision.fromBytes(List<int> rawKey) {
    if (rawKey.length != 16) {
      throw ArgumentError('La clave AES-128 debe tener exactamente 16 bytes');
    }
    _expandKey(Uint8List.fromList(rawKey));
  }

  /// Descifra un bloque de 16 bytes [src] a partir de [srcOffset] y lo escribe en [dst] en [dstOffset].
  void decryptBlock(
    Uint8List src,
    int srcOffset,
    Uint8List dst,
    int dstOffset,
  ) {
    // Cargar estado inicial desde src
    final state = Uint8List(16);
    for (var i = 0; i < 16; i++) {
      state[i] = src[srcOffset + i];
    }

    // AddRoundKey inicial con la última subclave (round 10)
    _addRoundKey(state, 10);

    // Rondas 9 descendiendo a 1
    for (var round = 9; round >= 1; round--) {
      _invShiftRows(state);
      _invSubBytes(state);
      _addRoundKey(state, round);
      _invMixColumns(state);
    }

    // Ronda final (round 0)
    _invShiftRows(state);
    _invSubBytes(state);
    _addRoundKey(state, 0);

    // Escribir en destino
    for (var i = 0; i < 16; i++) {
      dst[dstOffset + i] = state[i];
    }
  }

  /// Cifra un bloque de 16 bytes [src] a partir de [srcOffset] y lo escribe en [dst] en [dstOffset].
  /// Utilizado primordialmente para verificación y pruebas con vectores conocidos.
  void encryptBlock(
    Uint8List src,
    int srcOffset,
    Uint8List dst,
    int dstOffset,
  ) {
    final state = Uint8List(16);
    for (var i = 0; i < 16; i++) {
      state[i] = src[srcOffset + i];
    }

    // Round 0
    _addRoundKey(state, 0);

    // Rondas 1 a 9
    for (var round = 1; round <= 9; round++) {
      _subBytes(state);
      _shiftRows(state);
      _mixColumns(state);
      _addRoundKey(state, round);
    }

    // Ronda final (round 10)
    _subBytes(state);
    _shiftRows(state);
    _addRoundKey(state, 10);

    for (var i = 0; i < 16; i++) {
      dst[dstOffset + i] = state[i];
    }
  }

  /// Descifra en modo ECB sobre los bloques de 16 bytes dentro de [data] a partir de [offset] para [length] bytes.
  /// Modifica el buffer [data] in-place o devuelve un nuevo [Uint8List].
  Uint8List decryptBlocksInPlace(Uint8List data, int offset, int length) {
    final blockCount = length ~/ 16;
    final temp = Uint8List(16);
    for (var i = 0; i < blockCount; i++) {
      final blockOffset = offset + (i * 16);
      decryptBlock(data, blockOffset, temp, 0);
      data.setRange(blockOffset, blockOffset + 16, temp);
    }
    return data;
  }

  // ------------------------------------------------------------- Key Expansion
  void _expandKey(Uint8List key) {
    for (var i = 0; i < 4; i++) {
      _expandedKey[i] = ((key[4 * i] & 0xFF) << 24) |
          ((key[4 * i + 1] & 0xFF) << 16) |
          ((key[4 * i + 2] & 0xFF) << 8) |
          (key[4 * i + 3] & 0xFF);
    }

    for (var i = 4; i < 44; i++) {
      var temp = _expandedKey[i - 1];
      if (i % 4 == 0) {
        temp = _subWord(_rotWord(temp)) ^ (_rcon[i ~/ 4] << 24);
      }
      _expandedKey[i] = (_expandedKey[i - 4] ^ temp) & 0xFFFFFFFF;
    }
  }

  static int _rotWord(int w) {
    return (((w << 8) & 0xFFFFFF00) | ((w >>> 24) & 0xFF)) & 0xFFFFFFFF;
  }

  static int _subWord(int w) {
    return ((_sBox[(w >>> 24) & 0xFF] << 24) |
            (_sBox[(w >>> 16) & 0xFF] << 16) |
            (_sBox[(w >>> 8) & 0xFF] << 8) |
            _sBox[w & 0xFF]) &
        0xFFFFFFFF;
  }

  void _addRoundKey(Uint8List state, int round) {
    final offset = round * 4;
    for (var c = 0; c < 4; c++) {
      final w = _expandedKey[offset + c];
      state[c * 4] ^= (w >>> 24) & 0xFF;
      state[c * 4 + 1] ^= (w >>> 16) & 0xFF;
      state[c * 4 + 2] ^= (w >>> 8) & 0xFF;
      state[c * 4 + 3] ^= w & 0xFF;
    }
  }

  // -------------------------------------------------------- Decryption Rounds
  static void _invShiftRows(Uint8List s) {
    // Row 1: desplazar a la derecha 1 (o izquierda 3)
    final r1 = s[13];
    s[13] = s[9];
    s[9] = s[5];
    s[5] = s[1];
    s[1] = r1;

    // Row 2: desplazar a la derecha 2
    final r2a = s[2];
    final r2b = s[6];
    s[2] = s[10];
    s[6] = s[14];
    s[10] = r2a;
    s[14] = r2b;

    // Row 3: desplazar a la derecha 3 (o izquierda 1)
    final r3 = s[3];
    s[3] = s[7];
    s[7] = s[11];
    s[11] = s[15];
    s[15] = r3;
  }

  static void _invSubBytes(Uint8List s) {
    for (var i = 0; i < 16; i++) {
      s[i] = _invSBox[s[i]];
    }
  }

  static void _invMixColumns(Uint8List s) {
    for (var c = 0; c < 4; c++) {
      final i = c * 4;
      final a0 = s[i];
      final a1 = s[i + 1];
      final a2 = s[i + 2];
      final a3 = s[i + 3];

      s[i] = _mul14(a0) ^ _mul11(a1) ^ _mul13(a2) ^ _mul9(a3);
      s[i + 1] = _mul9(a0) ^ _mul14(a1) ^ _mul11(a2) ^ _mul13(a3);
      s[i + 2] = _mul13(a0) ^ _mul9(a1) ^ _mul14(a2) ^ _mul11(a3);
      s[i + 3] = _mul11(a0) ^ _mul13(a1) ^ _mul9(a2) ^ _mul14(a3);
    }
  }

  // -------------------------------------------------------- Encryption Rounds
  static void _shiftRows(Uint8List s) {
    final r1 = s[1];
    s[1] = s[5];
    s[5] = s[9];
    s[9] = s[13];
    s[13] = r1;

    final r2a = s[2];
    final r2b = s[6];
    s[2] = s[10];
    s[6] = s[14];
    s[10] = r2a;
    s[14] = r2b;

    final r3 = s[15];
    s[15] = s[11];
    s[11] = s[7];
    s[7] = s[3];
    s[3] = r3;
  }

  static void _subBytes(Uint8List s) {
    for (var i = 0; i < 16; i++) {
      s[i] = _sBox[s[i]];
    }
  }

  static void _mixColumns(Uint8List s) {
    for (var c = 0; c < 4; c++) {
      final i = c * 4;
      final a0 = s[i];
      final a1 = s[i + 1];
      final a2 = s[i + 2];
      final a3 = s[i + 3];

      s[i] = _mul2(a0) ^ _mul3(a1) ^ a2 ^ a3;
      s[i + 1] = a0 ^ _mul2(a1) ^ _mul3(a2) ^ a3;
      s[i + 2] = a0 ^ a1 ^ _mul2(a2) ^ _mul3(a3);
      s[i + 3] = _mul3(a0) ^ a1 ^ a2 ^ _mul2(a3);
    }
  }

  // ------------------------------------------------------- GF(2^8) Arithmetic
  static int _xtimes(int b) => ((b << 1) ^ ((b & 0x80) != 0 ? 0x1B : 0)) & 0xFF;
  static int _mul2(int b) => _xtimes(b);
  static int _mul3(int b) => _xtimes(b) ^ b;
  static int _mul4(int b) => _xtimes(_xtimes(b));
  static int _mul8(int b) => _xtimes(_xtimes(_xtimes(b)));
  static int _mul9(int b) => _mul8(b) ^ b;
  static int _mul11(int b) => _mul8(b) ^ _mul2(b) ^ b;
  static int _mul13(int b) => _mul8(b) ^ _mul4(b) ^ b;
  static int _mul14(int b) => _mul8(b) ^ _mul4(b) ^ _mul2(b);

